export const ALL_TASKS = UNITS.flatMap((unit) => unit.tasks.map((task) => ({ ...task, unitId: unit.id })));

export function findUnit(id) {
  return UNITS.find((unit) => unit.id === id) || null;
}

/** Everything the reader may return, so a wrong answer reads as the wrong word. */
export function answerWords() {
  const words = new Set();
  for (const task of ALL_TASKS) {
    for (const text of [task.answer, ...(task.accept || []), ...(task.distractors || []), ...(task.options || [])]) {
      if (!text) continue;
      for (const word of String(text).toLowerCase().split(/\s+/)) {
        const clean = word.replace(/[^a-z']/g, '');
        if (clean) words.add(clean);
      }
    }
  }
  return [...words];
}
