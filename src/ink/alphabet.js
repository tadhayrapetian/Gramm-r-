// Capitals that are simply the lowercase shape drawn at cap height.
const upperScaled = ['c', 'o', 's', 'u', 'v', 'w', 'x', 'z'];

/** @type {{label: string, strokes: number[][][], source: 'builtin', form: 'lower'|'upper'}[]} */
export const TEMPLATES = [];

for (const [label, variants] of Object.entries(lower)) {
  for (const strokes of variants) TEMPLATES.push({ label, strokes, source: 'builtin', form: 'lower' });
}
for (const [label, variants] of Object.entries(upper)) {
  for (const strokes of variants) TEMPLATES.push({ label, strokes, source: 'builtin', form: 'upper' });
}
for (const label of upperScaled) {
  TEMPLATES.push({ label, strokes: tall(lower[label][0]), source: 'builtin', form: 'upper' });
}

export const ALPHABET = Object.keys(lower);
