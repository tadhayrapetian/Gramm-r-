// Reference letterforms, drawn in the template coordinate system described in
// geometry.js (baseline y = 0, x-height = 1). Every shape is a list of strokes,
// each stroke a polyline; the recognizer resamples them, so two points are
// enough for a straight segment.
//
// Several letters carry more than one variant because people genuinely draw them
// differently (single- vs double-storey `g`, hooked vs plain `t`, ...). Capitals
// are stored under their lowercase label: answers are checked case-insensitively.

import { arc, bowl, join } from './geometry.js';

/** Scale a shape about the baseline — turns an x-height form into a cap-height one. */
function tall(strokes, s = 1.5) {
  return strokes.map((stroke) => stroke.map(([x, y]) => [x * s, y * s]));
}

